"""SQL detection metrics are exact and reproducible on the labelled datasets.

`fixture` (analytics/detection_fixture.csv, 33 rows, 13 attacks) - expected values computed by hand:
  baseline (any deny):  21 flagged -> TP 11, FP 10, FN 2 (e29, e30 were allowed), TN 10
  candidate (R1|R2|R3|R4): flags e15 e19 e20 e21 e22 e23 e24 e25 e26 e27 e31 e33
                        -> TP 10, FP 2 (e15 outage burst, e33 inactive-user retries), FN 3 (e28 e29 e30), TN 18

`large` (analytics/detection_large.csv, generated by scripts/gen_detection_dataset.py) - too large to
check by hand, so every SQL result is compared with an independent Python implementation of the same
rules (the oracle below), which is also run on the hand-checked fixture.
"""

from __future__ import annotations

import csv
from datetime import datetime, timedelta
from decimal import Decimal
from pathlib import Path
from typing import Any

import psycopg
import pytest

from tests.conftest import APP_DSN

pytestmark = pytest.mark.integration
ROOT = Path(__file__).resolve().parents[2]
FILES = {"fixture": "detection_fixture.csv", "large": "detection_large.csv"}


def q(name: str, dataset: str) -> list[tuple[Any, ...]]:
    """Run a committed query and keep the rows of one dataset (first column), without that column."""
    with psycopg.connect(APP_DSN) as conn:
        rows = conn.execute((ROOT / "analytics" / "queries" / name).read_text()).fetchall()  # type: ignore[call-overload]
    return [r[1:] for r in rows if r[0] == dataset]


def test_datasets_loaded() -> None:
    with psycopg.connect(APP_DSN) as conn:
        rows = conn.execute(
            "SELECT dataset, count(*), count(*) FILTER (WHERE ground_truth_is_attack) FROM detection_events"
            " GROUP BY dataset ORDER BY dataset"
        ).fetchall()
    assert rows == [("fixture", 33, 13), ("large", 1888, 143)]


def test_confusion_matrix_exact() -> None:
    rows = {r[0]: r[1:] for r in q("confusion_matrix.sql", "fixture")}
    assert rows["baseline_any_deny"] == (11, 10, 2, 10, Decimal("0.5238"), Decimal("0.8462"))
    assert rows["candidate_rules"] == (10, 2, 3, 18, Decimal("0.8333"), Decimal("0.7692"))


def test_by_rule_exact() -> None:
    rows = {r[0]: r[1:] for r in q("by_rule.sql", "fixture")}
    assert rows == {
        "r1_cross_tenant": (4, 0, Decimal("1.0000")),
        "r2_agent_out_of_scope": (3, 0, Decimal("1.0000")),
        "r3_token_forgery": (3, 0, Decimal("1.0000")),
        "r4_deny_burst": (4, 2, Decimal("0.6667")),
    }


def test_by_policy_version_exact() -> None:
    rows = {r[0]: r[1:] for r in q("by_policy_version.sql", "fixture")}
    assert rows == {"policy-v0": (1, 0, 1, 3, 1), "policy-v1": (9, 2, 2, 15, 1)}


def test_division_by_zero_protected() -> None:
    with psycopg.connect(APP_DSN) as conn:
        row = conn.execute("SELECT round(0::numeric / NULLIF(0, 0), 4)").fetchone()
    assert row == (None,)


# ----------------------------------------------------------------------------- independent oracle


def _flags(dataset: str) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = list(csv.DictReader((ROOT / "analytics" / FILES[dataset]).open()))
    for r in rows:
        r["t"] = datetime.fromisoformat(r["event_time"].replace("Z", "+00:00"))
        r["gt"] = r["ground_truth_is_attack"] == "true"
    denies: dict[str, list[datetime]] = {}
    for r in rows:
        if r["decision"] == "deny":
            denies.setdefault(r["principal_id"], []).append(r["t"])
    for r in rows:
        deny = r["decision"] == "deny"
        r["r0"] = deny
        r["r1"] = bool(r["resource_tenant"]) and r["resource_tenant"] != r["subject_tenant"]
        r["r2"] = (
            r["principal_type"] == "agent"
            and deny
            and any(
                k in r["reason_code"] for k in ("TASK_SCOPE_EXCEEDED", "UNKNOWN_TOOL", "RESTRICTED_VIA_AGENT")
            )
        )
        r["r3"] = r["action"] == "authn" and r["reason_code"] in (
            "INVALID_SIGNATURE",
            "DISALLOWED_ALGORITHM",
            "UNKNOWN_SIGNING_KEY",
            "WRONG_AUDIENCE",
            "MALFORMED_TOKEN",
        )
        window = [
            t for t in denies.get(r["principal_id"], []) if r["t"] - timedelta(minutes=5) <= t <= r["t"]
        ]
        r["r4"] = deny and len(window) >= 3
        r["cand"] = r["r1"] or r["r2"] or r["r3"] or r["r4"]
    return rows


def _matrix(rows: list[dict[str, Any]], key: str) -> tuple[int, int, int, int]:
    tp = sum(1 for r in rows if r["gt"] and r[key])
    fp = sum(1 for r in rows if not r["gt"] and r[key])
    fn = sum(1 for r in rows if r["gt"] and not r[key])
    tn = sum(1 for r in rows if not r["gt"] and not r[key])
    return tp, fp, fn, tn


@pytest.mark.parametrize("dataset", ["fixture", "large"])
def test_confusion_matrix_matches_oracle(dataset: str) -> None:
    sql = {r[0]: tuple(r[1:5]) for r in q("confusion_matrix.sql", dataset)}
    rows = _flags(dataset)
    assert sql == {"baseline_any_deny": _matrix(rows, "r0"), "candidate_rules": _matrix(rows, "cand")}


@pytest.mark.parametrize("dataset", ["fixture", "large"])
def test_by_rule_matches_oracle(dataset: str) -> None:
    sql = {r[0]: tuple(r[1:3]) for r in q("by_rule.sql", dataset)}
    rows = _flags(dataset)
    expected = {
        name: (sum(1 for r in rows if r[k] and r["gt"]), sum(1 for r in rows if r[k] and not r["gt"]))
        for name, k in (
            ("r1_cross_tenant", "r1"),
            ("r2_agent_out_of_scope", "r2"),
            ("r3_token_forgery", "r3"),
            ("r4_deny_burst", "r4"),
        )
    }
    assert sql == expected


@pytest.mark.parametrize("dataset", ["fixture", "large"])
def test_by_policy_version_matches_oracle(dataset: str) -> None:
    sql = {r[0]: tuple(r[1:]) for r in q("by_policy_version.sql", dataset)}
    rows = _flags(dataset)
    expected = {}
    for pv in sorted({r["policy_version"] for r in rows}):
        sub = [r for r in rows if r["policy_version"] == pv]
        expected[pv] = (*_matrix(sub, "cand"), sum(1 for r in sub if r["gt"] and r["decision"] == "allow"))
    assert sql == expected
